// Regenerates lib/localBusinessTypes.js from schema.org's own vocabulary:
// every type that is LocalBusiness or a subclass of it, at any depth
// (Dentist sits under LocalBusiness, MedicalBusiness and MedicalOrganization).
//
//   node scripts/gen-local-business-types.mjs
//
// Re-run when schema.org publishes a release that adds local business types.

import { writeFileSync } from 'node:fs';

const SOURCE = 'https://schema.org/version/latest/schemaorg-current-https.jsonld';
const ROOT = 'schema:LocalBusiness';

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`schema.org returned ${res.status}`);
const vocab = await res.json();

// Walk rdfs:subClassOf on every node, not only rdfs:Class ones: the medical
// specialties (Dermatology, Pediatric...) are declared as MedicalSpecialty
// values AND as subclasses of MedicalBusiness, and pages use them as types.
const children = new Map();
for (const node of vocab['@graph']) {
  const parents = [node['rdfs:subClassOf'] ?? []].flat().map((p) => p['@id']);
  for (const parent of parents) {
    if (!children.has(parent)) children.set(parent, new Set());
    children.get(parent).add(node['@id']);
  }
}

const seen = new Set();
const stack = [ROOT];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  stack.push(...(children.get(id) ?? []));
}

// Name each type by its id ("schema:Dentist" -> "Dentist"): that is what
// pages put in @type, and some rdfs:label values are language objects.
const names = [...seen]
  .filter((id) => id.startsWith('schema:'))
  .map((id) => id.slice('schema:'.length))
  .sort();
if (!names.includes('LocalBusiness') || names.length < 100) {
  throw new Error(`Unexpected result (${names.length} types); not writing the file`);
}

const today = new Date().toISOString().slice(0, 10);
const body = `// GENERATED by scripts/gen-local-business-types.mjs on ${today} from
// ${SOURCE}
// Do not edit by hand: re-run the script.
//
// LocalBusiness and every schema.org subtype of it (${names.length} types). A page
// that marks itself up as any of these has LocalBusiness structured data:
// a dentist's "Dentist" or a plumber's "Plumber" is a LocalBusiness.

export const LOCAL_BUSINESS_TYPE_NAMES = [
${names.map((n) => `  '${n}',`).join('\n')}
];

export const LOCAL_BUSINESS_TYPES = new Set(LOCAL_BUSINESS_TYPE_NAMES);
`;

writeFileSync(new URL('../lib/localBusinessTypes.js', import.meta.url), body);
console.log(`Wrote ${names.length} types to lib/localBusinessTypes.js`);
