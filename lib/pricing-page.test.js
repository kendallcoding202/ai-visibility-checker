import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import Page, { generateMetadata } from '../app/pricing/page.js';
import sitemap from '../app/sitemap.js';
import { checkBrandHref } from './checkLink.js';
import { freeChecker, tracker } from './costCompare.js';
import { PAID_REPORT_PRICE } from './paidReport.js';
import { TRACKING_TIER_PRICE } from './trackingTier.js';

test('the pricing page renders $24/month and $19, and no card only on the free check', () => {
  const metadata = generateMetadata();
  assert.equal(metadata.title, 'AI Visibility Checker pricing');
  assert.equal(metadata.alternates.canonical, '/pricing');
  assert.equal(metadata.description, `Free check, a one-time report at ${PAID_REPORT_PRICE}, and monthly tracking at ${TRACKING_TIER_PRICE}. The Apify tracker is $${tracker.pricePerAnswer} per answer on the Free tier. Prices checked Nov 23, 2026.`);
  assert.equal(metadata.openGraph.description, metadata.description);
  assert.equal(metadata.twitter.description, metadata.description);
  assert.equal(metadata.description.includes('$15'), false);
  const html = renderToStaticMarkup(createElement(Page));
  assert.equal(html.includes('<h1>Pricing</h1>'), true);
  assert.equal(html.includes(TRACKING_TIER_PRICE), true);
  assert.equal(html.includes('$24/month'), true);
  assert.equal(html.includes(PAID_REPORT_PRICE), true);
  assert.equal(html.includes('$19'), true);
  assert.equal(html.includes(`${freeChecker.checksPerIpPerDay} free checks per day`), true);
  assert.equal(html.includes('confirmed email for that brand'), true);
  assert.equal(html.includes('Prices checked Nov 23, 2026. Stripe processes payments; we do not store card numbers.'), true);
  assert.equal(html.includes('application/ld+json'), false);
  const start = html.indexOf('id="free-check"');
  const end = html.indexOf('</article>', start);
  assert.equal(start > -1 && end > start, true);
  const free = html.slice(start, end).toLowerCase();
  const rest = (html.slice(0, start) + html.slice(end)).toLowerCase();
  assert.equal(free.includes('no card'), true);
  assert.equal(rest.includes('no card'), false);
});

test('pricing is linked from the footer, sitemap, and llms.txt', () => {
  const footer = readFileSync(new URL('../app/Footer.js', import.meta.url), 'utf8');
  const home = readFileSync(new URL('../app/page.js', import.meta.url), 'utf8');
  assert.equal(footer.includes('href="/pricing"'), true);
  assert.equal(home.includes('href="/pricing"'), true);
  const entry = sitemap().find((item) => item.url === 'https://aivisibilitychecker.app/pricing');
  assert.equal(Boolean(entry), true);
  assert.equal(entry.lastModified.toISOString().startsWith('2026-11-23'), true);
  const llms = readFileSync(new URL('../public/llms.txt', import.meta.url), 'utf8');
  assert.equal(llms.includes('https://aivisibilitychecker.app/pricing'), true);
  assert.equal(checkBrandHref('/pricing'), '/#checker');
});
